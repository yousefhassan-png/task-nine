# --- التمرين 1: دالة Z-score ---
# (أسماء الدوال مطلوبة من التاسك بالإنجليزية، أما باقي الأسماء فبالعربية)
def detect_outliers_zscore(البيانات, العمود):
    # الخطوة 1: المتوسط والانحراف المعياري للعمود
    المتوسط = البيانات[العمود].mean()
    الانحراف_المعياري = البيانات[العمود].std()
    # الخطوة 2: Z-score لكل قيمة = (القيمة - المتوسط) / الانحراف المعياري
    قيم_z = (البيانات[العمود] - المتوسط) / الانحراف_المعياري
    # الخطوة 3: نأخذ الصفوف التي Z-score لها أكبر من 3 أو أصغر من -3
    الصفوف_الشاذة = البيانات[(قيم_z > 3) | (قيم_z < -3)]
    return الصفوف_الشاذة


# --- دالة IQR (الطريقة التي تعلمناها بتاسك 2) ---
def detect_outliers_iqr(البيانات, العمود):
    الربيع_الأول = البيانات[العمود].quantile(0.25)    # Q1
    الربيع_الثالث = البيانات[العمود].quantile(0.75)   # Q3
    المدى_الربيعي = الربيع_الثالث - الربيع_الأول        # IQR = Q3 - Q1
    الحد_الأدنى = الربيع_الأول - 1.5 * المدى_الربيعي
    الحد_الأعلى = الربيع_الثالث + 1.5 * المدى_الربيعي
    # أي قيمة خارج الحدين تعتبر شاذة
    الصفوف_الشاذة = البيانات[(البيانات[العمود] < الحد_الأدنى) | (البيانات[العمود] > الحد_الأعلى)]
    return الصفوف_الشاذة


